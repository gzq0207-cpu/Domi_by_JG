test("an empty queue or a live worker lock never starts the independent browser",async t=>{
  const f=fixture(t),previous=process.env.FOLLOW_BUILDERS_HOME;process.env.FOLLOW_BUILDERS_HOME=f.root;
  try {
    fs.writeFileSync(path.join(f.root,"config.json"),JSON.stringify({archive:{provider:"chatgpt",browser:{launcher:path.join(f.root,"must-not-run.exe")}}}));
    fs.writeFileSync(path.join(f.root,"pending-archive.json"),JSON.stringify({items:[]}));
    const {main}=require("./process-subscription-archives.cjs");
    assert.equal((await main()).remaining,0);
    fs.writeFileSync(path.join(f.root,"pending-archive.json"),JSON.stringify({items:[{...f.item,status:"pending"}]}));
    fs.writeFileSync(path.join(f.root,".archive.lock"),String(process.pid));
    assert.equal((await main()).busy,true);
  } finally { if(previous===undefined)delete process.env.FOLLOW_BUILDERS_HOME;else process.env.FOLLOW_BUILDERS_HOME=previous; }
});
