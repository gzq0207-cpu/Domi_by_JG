test("interrupted acquisition resumes the exact browser receipt instead of re-exporting",async t=>{
  const f=fixture(t),stateRoot=path.join(f.root,"archives");let exported=0,receipts=0;
  const first=new TabbitCaptionAcquirer({stateRoot,run:async(exe,args)=>{
    if(args[0]==="create")return reply({task:{}});exported++;throw new BrowserTranscriptError("BROWSER_CLI_TIMEOUT","transport stopped");}});
  await assert.rejects(first.acquire(f.item),/transport stopped/);assert.ok(fs.existsSync(first.activeRequestPath));
  const resumed=new TabbitCaptionAcquirer({stateRoot,run:async(exe,args)=>{
    if(args[0]==="create")return reply({task:{}});if(args[0]==="receipt"){receipts++;return reply({status:"succeeded",result:{type:"inline",value:f.value}});}
    if(args[0]==="finish")return reply({finished:true});
    assert.ok(args.find(a=>a.startsWith("cleanup-")));return reply({status:"succeeded",result:{value:{closed:true}}});}});
  assert.equal((await resumed.acquire(f.item)).validation.cueCount,21);assert.equal(exported,1);assert.equal(receipts,1);
  assert.equal(fs.existsSync(resumed.activeRequestPath),false);await resumed.close();
});

test("official transcript HTTP errors are preserved instead of being labelled as loading",async t=>{
  const f=fixture(t),issue={code:"REQUEST_HTTP_ERROR",origin:"https://www.youtube.com",
    details:{method:"POST",path:"/youtubei/v1/get_transcript",status:400}};
  const value={ok:false,code:"CAPTIONS_PENDING",message:"panel loading"};
  for(const resume of [false,true]) {
    const service=new TabbitCaptionAcquirer({stateRoot:path.join(f.root,"archives"),run:async(exe,args)=>{
      assert.equal(args[0],resume?"receipt":"nodejs");
      return reply(resume ? {status:"succeeded",outcome:{issuesDelta:[issue]},result:{type:"inline",value}}
        : {status:"succeeded",result:{value,issuesDelta:[issue]}});
    }});
    const result=await service.program("return {};","original-transcript-request",resume);
    assert.equal(result.code,"TRANSCRIPT_HTTP_ERROR");assert.equal(result.httpStatus,400);
    assert.match(result.message,/HTTP 400/);
  }
  const service=new TabbitCaptionAcquirer({stateRoot:path.join(f.root,"archives"),run:async()=>
    reply({status:"succeeded",result:{value,issuesDelta:[{...issue,details:{path:"/videoplayback",status:403}}]}})});
  assert.equal((await service.program("return {};","unrelated-media-error")).code,"CAPTIONS_PENDING");
  service.run=async()=>reply({status:"succeeded",result:{value:{ok:true},issuesDelta:[issue]}});
  assert.equal((await service.program("return {};","complete-transcript")).ok,true);
});

