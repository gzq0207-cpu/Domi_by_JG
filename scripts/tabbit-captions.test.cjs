test("normal browser export is durable, cached and independent of chat browser tools",async t=>{
  const f=fixture(t),calls=[];
  const run=async(exe,args,opts)=>{calls.push({exe,args,code:opts.input});if(args[0]==="create")return reply({task:{reused:true}});
    if(args[0]==="finish")return reply({finished:true});
    return reply({status:"succeeded",result:{value:args.includes("cleanup")?{closed:true}:f.value}});};
  const service=new TabbitCaptionAcquirer({stateRoot:path.join(f.root,"archives"),run});
  const result=await service.acquire(f.item);assert.equal(result.validation.cueCount,21);
  const before=calls.length;assert.equal((await service.acquire(f.item)).sourceSha256,result.sourceSha256);assert.equal(calls.length,before);
  const manifest=JSON.parse(fs.readFileSync(service.manifestPath,"utf8"));assert.equal(manifest.length,1);
  assert.ok(fs.existsSync(manifest[0].platformResponsePath));assert.equal(fs.existsSync(service.activeRequestPath),false);
  assert.ok(calls.some(c=>c.code?.includes("page.fetch")));
  assert.ok(calls.every(c=>!c.code||!/document\.cookie|localStorage|cookies\(/.test(c.code)));
  await service.close();
});

