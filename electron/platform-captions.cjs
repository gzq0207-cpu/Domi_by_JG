const ACQUISITION = "tabbit.youtube-platform-captions";
const PANEL_ACQUISITION = "tabbit.youtube-transcript-panel";

function clock(seconds) {
  const n = Math.floor(seconds);
  return n >= 3600 ? `${Math.floor(n / 3600)}:${String(Math.floor(n / 60) % 60).padStart(2, "0")}:${String(n % 60).padStart(2, "0")}`
    : `${Math.floor(n / 60)}:${String(n % 60).padStart(2, "0")}`;
}

function platformCaptionExport(source) {
  if (source?.version !== 1 || ![ACQUISITION,PANEL_ACQUISITION].includes(source.acquisition)
      || !/^[A-Za-z0-9_-]{11}$/.test(source.videoId || "") || typeof source.title !== "string" || !source.title.trim()
      || !Number.isFinite(source.durationSeconds) || source.durationSeconds <= 0
      || !/^[A-Za-z0-9-]{1,32}$/.test(source.language || "") || typeof source.autoGenerated !== "boolean"
      || (source.acquisition === ACQUISITION && !Array.isArray(source.response?.events))) throw new Error("平台字幕响应、视频标识或时长无效。");
  if (source.acquisition === PANEL_ACQUISITION) return panelCaptionExport(source).text;
  const rows = [];
  for (const event of source.response.events) {
    // JSON3 also contains empty timing/style events. Preserve all text-bearing
    // events, including repeated speech and rolling captions, without deduping.
    if (!Array.isArray(event.segs)) continue;
    if (event.segs.some(segment => typeof segment.utf8 !== "string")) throw new Error("平台字幕包含未支持的文本片段。");
    const text = event.segs.map(segment => segment.utf8).join("").replace(/\s+/g, " ").trim();
    if (!text) continue;
    if (!Number.isFinite(event.tStartMs) || event.tStartMs < 0) throw new Error("平台字幕缺少真实起始时间。");
    rows.push(`[${clock(event.tStartMs / 1000)}] ${text}`);
  }
  if (!rows.length) throw new Error("平台字幕响应为空，不能归档。");
  return ["YouTube transcript", `Video ID: ${source.videoId}`, `Language: ${source.language}`,
    `Captions: ${source.autoGenerated ? "auto-generated" : "authored or unspecified"}`, "", ...rows].join("\n") + "\n";
}

function panelCaptionExport(source) {
  const sections = source.response?.contents;
  if (!Array.isArray(sections) || !Array.isArray(source.displayedSegments)) throw new Error("官方文字稿面板数据不完整。");
  const rows = []; let expectedIndex = 0;
  const clean = text => String(text).replace(/\s+/g," ").trim();
  for (const entry of sections) {
    const section = entry.itemSectionRenderer;
    if (!section || !Array.isArray(section.contents)) throw new Error("官方文字稿存在未读取的分页或未知章节。");
    const header = section.header?.macroMarkersPanelItemViewModel;
    if (header && header.index !== expectedIndex++) throw new Error("官方文字稿章节索引存在缺口。");
    for (const record of section.contents) {
      const item = record.macroMarkersPanelItemViewModel;
      if (!item || item.index !== expectedIndex++) throw new Error("官方文字稿字幕索引存在缺口，不能省略归档。");
      const endpoint = item.onTap?.innertubeCommand?.watchEndpoint;
      const timeline = item.item?.timelineItemViewModel;
      const segment = timeline?.contentItems?.[0]?.transcriptSegmentViewModel;
      if (!segment || timeline.contentItems.length !== 1 || endpoint?.videoId !== source.videoId
          || !/^\d+(?::\d{2}){1,2}$/.test(segment.timestamp || "") || typeof segment.simpleText !== "string")
        throw new Error("官方文字稿视频、时间戳或文本格式不匹配。");
      const start = segment.timestamp.split(":").reduce((sum, part) => sum * 60 + Number(part),0);
      if (start !== endpoint.startTimeSeconds || timeline.timestamp !== segment.timestamp) throw new Error("官方文字稿跳转时间与字幕时间不一致。");
      rows.push({timestamp:segment.timestamp,text:clean(segment.simpleText)});
    }
  }
  if (!rows.length || JSON.stringify(rows) !== JSON.stringify(source.displayedSegments.map(row=>({timestamp:row.timestamp,text:clean(row.text)}))))
    throw new Error("官方文字稿完整数据与全部显示字幕行不一致。");
  return { text:["YouTube transcript",`Video ID: ${source.videoId}`,`Language: ${source.language}`,
    `Captions: ${source.autoGenerated ? "auto-generated" : "authored or unspecified"}`,"",...rows.map(row=>`[${row.timestamp}] ${row.text}`)].join("\n")+"\n",
    proof:{sourceSegmentCount:rows.length,sourceIndexedItems:expectedIndex,omissionCheck:"contiguous-platform-indices-and-full-dom-match"} };
}

module.exports = { ACQUISITION, PANEL_ACQUISITION, clock, platformCaptionExport, panelCaptionExport };
