// Page data fields and normal caption-asset requests follow Tabbit's packaged
// YouTube playbook (TabbitAi/tabbit-webmcp, 13fef01b80ce371aeb53cf92bd3c677bb25c24bd).
// No account data, credentials, cookies or alternate YouTube clients are read.
function inspectYouTubePage({ videoId }) {
  const fail = (code, message) => ({ state: "blocked", code, message });
  if (location.protocol !== "https:" || location.hostname !== "www.youtube.com"
      || location.pathname !== "/watch" || new URL(location.href).searchParams.get("v") !== videoId)
    return fail("PAGE_CHANGED", "原视频页面已改变，停止字幕获取。");
  const playerElement = document.querySelector("#movie_player");
  const visibleError = [...document.querySelectorAll("yt-player-interstitial-renderer, yt-player-error-message-renderer, .ytp-error")]
    .filter(el => el.getBoundingClientRect().width && el.getBoundingClientRect().height)
    .map(el => el.textContent).join(" ").replace(/\s+/g, " ").slice(0, 900);
  if (/验证码|captcha/i.test(visibleError)) return fail("CAPTCHA_REQUIRED", "YouTube 页面要求验证码，等待用户正常完成验证。");
  if (/请登录|sign in|not a bot|不是聊天机器人/i.test(visibleError))
    return fail("AUTH_REQUIRED", "YouTube 页面要求登录以确认不是聊天机器人，等待用户正常登录。");
  if (/未连接到互联网|offline|internet connection/i.test(visibleError)) return fail("NETWORK_UNAVAILABLE", "YouTube 页面显示未连接到互联网。");
  if (/not available in your country|地区|区域|members.only|会员|购买|purchase|rent/i.test(visibleError))
    return fail("CONTENT_RESTRICTED", "YouTube 页面显示地区、会员或付费访问限制。");
  const normalize = value => { if (typeof value !== "string") return value; try { return JSON.parse(value); } catch { return null; } };
  const candidates = [globalThis.ytInitialPlayerResponse, globalThis.ytplayer?.config?.args?.raw_player_response,
    document.querySelector("ytd-watch-flexy")?.playerData, document.querySelector("ytd-watch-flexy")?.data?.playerData].map(normalize);
  const current = candidates.find(value => value?.videoDetails?.videoId === videoId);
  const status = current?.playabilityStatus || candidates.find(value => !value?.videoDetails?.videoId)?.playabilityStatus;
  if (status?.status === "LOGIN_REQUIRED") return fail("AUTH_REQUIRED", "YouTube 播放器要求正常登录。");
  if (status?.status && !["OK", "LIVE_STREAM_OFFLINE"].includes(status.status))
    return fail("CONTENT_RESTRICTED", `YouTube 播放器访问受限（${String(status.status).slice(0, 50)}）。`);
  const headings = [...document.querySelectorAll("h1")].filter(element => element.getBoundingClientRect().width && element.getBoundingClientRect().height)
    .map(element => element.textContent?.trim()).filter(Boolean);
  const title = current?.videoDetails?.title ? headings.find(text => text === current.videoDetails.title) : headings[0];
  const seconds = Number(current?.videoDetails?.lengthSeconds);
  const video = playerElement?.querySelector("video");
  const clockText = playerElement?.querySelector(".ytp-time-duration")?.textContent?.trim() || "";
  const displayedDuration = /^\d+(?::\d{2}){1,2}$/.test(clockText)
    ? clockText.split(":").reduce((sum, part) => sum * 60 + Number(part), 0) : NaN;
  const actualDuration = displayedDuration > 0 ? displayedDuration : video?.duration;
  if (!current || !title || !Number.isFinite(seconds) || seconds <= 0 || !Number.isFinite(actualDuration)
      || playerElement?.classList.contains("ad-showing") || Math.abs(actualDuration - seconds) > 2)
    return { state: "loading", code: "PLAYER_LOADING", message: "等待原视频标题、资料和真实播放器时长加载完整。" };
  if (status?.status === "LIVE_STREAM_OFFLINE")
    return { state: "loading", code: "LIVE_NOT_FINISHED", message: "直播尚未结束，等待完整字幕。" };
  const tracks = current.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];
  if (!tracks.length) return { state: "loading", code: "CAPTIONS_PENDING", message: "原视频字幕轨尚未就绪，保留后续补取。" };
  const track = tracks.find(t => /^en(?:-|$)/i.test(t.languageCode) && t.kind !== "asr")
    || tracks.find(t => /^en(?:-|$)/i.test(t.languageCode)) || tracks[0];
  if (!track.baseUrl) return fail("CAPTION_URL_MISSING", "平台字幕轨没有提供可下载的字幕地址。");
  const url = new URL(track.baseUrl, location.href);
  if (url.protocol !== "https:" || url.hostname !== "www.youtube.com" || url.pathname !== "/api/timedtext" || url.username || url.password)
    return fail("CAPTION_ORIGIN_INVALID", "平台字幕地址不在已核验的原站字幕入口内。");
  url.searchParams.set("fmt", "json3");
  return { state: "ready", videoId, title, durationSeconds: seconds, actualPlayerDurationSeconds: actualDuration,
    language: track.languageCode, autoGenerated: track.kind === "asr", captionUrl: url.href };
}

function buildCaptionProgram(item) {
  if (!/^[A-Za-z0-9_-]{11}$/.test(item.videoId || "") || item.url !== `https://www.youtube.com/watch?v=${item.videoId}`)
    throw new Error("订阅视频标识或链接无效。");
  return `
const input = ${JSON.stringify({ videoId: item.videoId, url: item.url })};
if (new URL(page.url()).hostname === "accounts.google.com") return {ok:false,code:"AUTH_REQUIRED",message:"请先在保留的登录页完成正常登录。"};
if (page.url() !== input.url) await page.goto(input.url, {waitUntil:"domcontentloaded", timeout:35000});
const mute=page.getByRole("button",{name:/^(?:静音|Mute) \\(m\\)$/i});
if(await mute.count()===1) await mute.click({timeout:2000}).catch(()=>{});
const skip=page.getByRole("button",{name:/^(?:跳过|Skip(?: ads?)?)$/i});
if(await skip.count()===1) await skip.click({timeout:2000}).catch(()=>{});
const inspect = ${inspectYouTubePage.toString()};
let state = await page.evaluate(inspect, input);
if (state.state === "loading") {
  try { await page.waitForFunction(input => {
    const inspect = ${inspectYouTubePage.toString()};
    return inspect(input).state !== "loading";
  }, input, {timeout:35000, polling:500}); } catch {}
  state = await page.evaluate(inspect, input);
}
if (state.state !== "ready") {
  if (["AUTH_REQUIRED","CAPTCHA_REQUIRED"].includes(state.code)) reportIssue("AUTHENTICATION_REQUIRED");
  return {ok:false,code:state.code,message:state.message,url:page.url()};
}
let response; try { response = await page.fetch(state.captionUrl, {as:"text", credentials:"same-origin", maxBytes:5*1024*1024, timeoutMs:20000}); }
catch {response={ok:false,status:0};}
if(response.status===429) return {ok:false,code:"RATE_LIMITED",message:"平台字幕入口限流，保留后续重试。"};
let payload; if(response.ok&&response.text?.trim()) {try{payload=JSON.parse(response.text);}catch{}}
let acquisition="tabbit.youtube-platform-captions",displayedSegments;
if(!Array.isArray(payload?.events)||!payload.events.some(event=>event.segs?.some(segment=>segment.utf8?.trim()))) {
  // Use the same browser's normal, official transcript UI when the platform's
  // caption asset is temporarily empty. Never change clients or generate tokens.
  const expand=page.getByRole("button",{name:/^(?:\\.\\.\\.|…)?\\s*(?:更多|more|show more)\\s*$/i});
  if(await expand.count()) await expand.first().click({timeout:10000});
  await page.getByRole("button",{name:/^(?:内容转文字|显示转录内容|Show transcript)$/i}).first().click({timeout:10000});
  try { await page.waitForFunction(()=>{
    const panel=[...document.querySelectorAll('ytd-engagement-panel-section-list-renderer[target-id="PAmodern_transcript_view"]')]
      .find(element=>element.getBoundingClientRect().width&&element.getBoundingClientRect().height);
    return panel?.querySelectorAll("transcript-segment-view-model").length>0;
  },undefined,{timeout:30000}); } catch {return {ok:false,code:"CAPTIONS_PENDING",message:"官方文字稿面板仍在加载，保留后续补取。"};}
  const panelData=await page.evaluate(()=>{
    const panel=[...document.querySelectorAll('ytd-engagement-panel-section-list-renderer[target-id="PAmodern_transcript_view"]')]
      .find(element=>element.getBoundingClientRect().width&&element.getBoundingClientRect().height);
    return {response:panel?.data?.content?.sectionListRenderer,displayedSegments:[...(panel?.querySelectorAll("transcript-segment-view-model")||[])].map(element=>({
      timestamp:element.querySelector(".ytwTranscriptSegmentViewModelTimestamp")?.textContent?.trim(),text:element.querySelector('span[role="text"]')?.textContent}))};
  });
  if(!panelData.response||!panelData.displayedSegments.length)return {ok:false,code:"CAPTION_FORMAT_INVALID",message:"官方文字稿结构尚不能完整核验。"};
  acquisition="tabbit.youtube-transcript-panel";payload=panelData.response;displayedSegments=panelData.displayedSegments;
}
const after = await page.evaluate(inspect,input);
if (after.state !== "ready" || after.videoId !== state.videoId || after.durationSeconds !== state.durationSeconds || after.title !== state.title)
  return {ok:false,code:"PAGE_CHANGED",message:"字幕获取期间原视频资料发生变化，停止导出。"};
const raw={version:1,acquisition,videoId:state.videoId,title:state.title,durationSeconds:state.durationSeconds,
  language:state.language,autoGenerated:state.autoGenerated,response:payload,...(displayedSegments?{displayedSegments}:{})};
const {writeFile}=await import("node:fs/promises");
const file=artifactPath(input.videoId+"-"+Date.now()+"-platform-response.json");
await writeFile(file,JSON.stringify(raw),{encoding:"utf8",flag:"wx"});
return {ok:true,videoId:state.videoId,title:state.title,durationSeconds:state.durationSeconds,actualPlayerDurationSeconds:state.actualPlayerDurationSeconds,
  language:state.language,autoGenerated:state.autoGenerated,platformResponsePath:file};
`;
}

module.exports = { inspectYouTubePage, buildCaptionProgram };
